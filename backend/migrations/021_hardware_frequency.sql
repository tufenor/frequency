BEGIN;

ALTER TABLE public.planos_frequency
    ADD COLUMN max_monitores integer NOT NULL DEFAULT 0,
    ADD COLUMN max_leitores integer NOT NULL DEFAULT 0,
    ADD CONSTRAINT planos_frequency_max_monitores_check CHECK (max_monitores >= 0),
    ADD CONSTRAINT planos_frequency_max_leitores_check CHECK (max_leitores >= 0);

UPDATE public.planos_frequency
SET max_monitores = CASE nivel
        WHEN 'essencial' THEN 1
        WHEN 'profissional' THEN 3
        WHEN 'premium' THEN 15
        ELSE 0
    END,
    max_leitores = CASE nivel
        WHEN 'essencial' THEN 1
        WHEN 'profissional' THEN 3
        WHEN 'premium' THEN 15
        ELSE 0
    END;

CREATE TABLE public.monitores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id integer NOT NULL REFERENCES public.academias(id) ON DELETE CASCADE,
    nome text NOT NULL,
    chave_hash text NOT NULL UNIQUE CHECK (chave_hash ~ '^[0-9a-f]{64}$'),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX monitores_academia_ativos_idx
    ON public.monitores (academia_id, ativo);

INSERT INTO public.monitores (academia_id, nome, chave_hash)
SELECT id, 'Monitor principal', chave_monitor_hash
FROM public.academias
WHERE chave_monitor_hash IS NOT NULL
ON CONFLICT (chave_hash) DO NOTHING;

ALTER TABLE public.leitores
    ADD COLUMN tipo_integracao text NOT NULL DEFAULT 'api_key',
    ADD COLUMN endpoint_url text,
    ADD COLUMN metodo_http text NOT NULL DEFAULT 'POST',
    ADD COLUMN configuracao jsonb NOT NULL DEFAULT '{}'::jsonb,
    ADD CONSTRAINT leitores_tipo_integracao_check CHECK (
        tipo_integracao IN ('api_key', 'http_json', 'webhook')
    ),
    ADD CONSTRAINT leitores_metodo_http_check CHECK (metodo_http IN ('POST', 'PUT', 'PATCH'));

COMMENT ON COLUMN public.planos_frequency.max_monitores IS
    'Quantidade máxima de telas de aluno ativas nesta assinatura.';
COMMENT ON COLUMN public.planos_frequency.max_leitores IS
    'Quantidade máxima de leitores/catracas ativas nesta assinatura.';
COMMENT ON TABLE public.monitores IS
    'Chaves independentes para telas de aluno; a chave antiga da academia é mantida por compatibilidade.';
COMMENT ON COLUMN public.leitores.tipo_integracao IS
    'Adaptador normalizado: api_key para integração existente, http_json ou webhook para APIs configuráveis.';

COMMIT;
