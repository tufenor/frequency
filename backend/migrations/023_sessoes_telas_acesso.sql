BEGIN;

CREATE TABLE public.monitor_sessoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id bigint NOT NULL REFERENCES public.monitores(id) ON DELETE CASCADE,
    sessao_hash text NOT NULL CHECK (sessao_hash ~ '^[0-9a-f]{64}$'),
    numero smallint NOT NULL CHECK (numero BETWEEN 1 AND 50),
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_sinal timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ativo boolean NOT NULL DEFAULT true,
    UNIQUE (monitor_id, sessao_hash),
    UNIQUE (monitor_id, numero)
);
CREATE INDEX monitor_sessoes_ativas_idx
    ON public.monitor_sessoes (monitor_id, ativo, ultimo_sinal);

ALTER TABLE public.presencas
    ADD COLUMN monitor_session_id bigint;

ALTER TABLE public.presencas
    ADD CONSTRAINT presencas_monitor_session_fk
        FOREIGN KEY (monitor_session_id)
        REFERENCES public.monitor_sessoes(id) ON DELETE SET NULL;

CREATE INDEX presencas_monitor_session_cursor_idx
    ON public.presencas (academia_id, monitor_session_id, id);

COMMENT ON TABLE public.monitor_sessoes IS
    'Janelas de tela independentes que compartilham o código do monitor.';

COMMIT;
