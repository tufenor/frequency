-- Reservas de aulas e áreas com capacidade por academia.
-- Esta migração é aditiva: restauração de backup é o mecanismo de reversão.
BEGIN;

CREATE TABLE public.recursos_agendaveis (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id integer NOT NULL REFERENCES public.academias(id) ON DELETE RESTRICT,
    nome text NOT NULL,
    tipo text NOT NULL CHECK (tipo IN ('aula', 'area')),
    descricao text NOT NULL DEFAULT '',
    capacidade integer NOT NULL CHECK (capacidade BETWEEN 1 AND 10000),
    ativo boolean NOT NULL DEFAULT TRUE,
    criado_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT recursos_agendaveis_nome_key UNIQUE (academia_id, nome),
    CONSTRAINT recursos_agendaveis_academia_id_id_key UNIQUE (academia_id, id)
);

CREATE TABLE public.sessoes_agendadas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id integer NOT NULL REFERENCES public.academias(id) ON DELETE RESTRICT,
    recurso_id bigint NOT NULL,
    inicio timestamptz NOT NULL,
    fim timestamptz NOT NULL,
    status text NOT NULL DEFAULT 'agendada'
        CHECK (status IN ('agendada', 'cancelada', 'encerrada')),
    criada_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT sessoes_recurso_mesma_academia_fk
        FOREIGN KEY (academia_id, recurso_id)
        REFERENCES public.recursos_agendaveis (academia_id, id)
        ON DELETE RESTRICT,
    CONSTRAINT sessoes_periodo_check CHECK (fim > inicio),
    CONSTRAINT sessoes_agendadas_academia_id_id_key UNIQUE (academia_id, id)
);

CREATE TABLE public.reservas_agendadas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id integer NOT NULL REFERENCES public.academias(id) ON DELETE RESTRICT,
    sessao_id bigint NOT NULL,
    aluno_id integer NOT NULL,
    status text NOT NULL DEFAULT 'reservada'
        CHECK (status IN ('reservada', 'cancelada')),
    criada_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelada_em timestamptz,
    CONSTRAINT reservas_sessao_mesma_academia_fk
        FOREIGN KEY (academia_id, sessao_id)
        REFERENCES public.sessoes_agendadas (academia_id, id)
        ON DELETE RESTRICT,
    CONSTRAINT reservas_aluno_mesma_academia_fk
        FOREIGN KEY (academia_id, aluno_id)
        REFERENCES public.alunos (academia_id, id)
        ON DELETE RESTRICT,
    CONSTRAINT reservas_cancelamento_check
        CHECK ((status = 'cancelada') = (cancelada_em IS NOT NULL)),
    CONSTRAINT reservas_agendadas_academia_id_id_key UNIQUE (academia_id, id)
);

CREATE UNIQUE INDEX reservas_ativas_sessao_aluno_uidx
    ON public.reservas_agendadas (sessao_id, aluno_id)
    WHERE status = 'reservada';

CREATE INDEX sessoes_agendadas_academia_inicio_idx
    ON public.sessoes_agendadas (academia_id, inicio, status);

CREATE INDEX reservas_agendadas_academia_sessao_idx
    ON public.reservas_agendadas (academia_id, sessao_id, status);

CREATE INDEX reservas_agendadas_academia_aluno_idx
    ON public.reservas_agendadas (academia_id, aluno_id, status);

COMMIT;
