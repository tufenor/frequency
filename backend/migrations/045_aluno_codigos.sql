-- Códigos de primeiro acesso (6 dígitos, guardados só como hash). Migração aditiva.
BEGIN;

CREATE TABLE public.aluno_codigos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id integer NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
    codigo_hash text NOT NULL CHECK (char_length(codigo_hash) = 64),
    criado_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em timestamptz NOT NULL,
    tentativas integer NOT NULL DEFAULT 0 CHECK (tentativas >= 0),
    usado_em timestamptz,
    ticket_hash text CHECK (ticket_hash IS NULL OR char_length(ticket_hash) = 64),
    ticket_expira_em timestamptz,
    ticket_usado_em timestamptz
);

CREATE INDEX aluno_codigos_aluno_idx ON public.aluno_codigos (aluno_id, criado_em DESC);
CREATE UNIQUE INDEX aluno_codigos_ticket_uidx ON public.aluno_codigos (ticket_hash) WHERE ticket_hash IS NOT NULL;

COMMIT;
