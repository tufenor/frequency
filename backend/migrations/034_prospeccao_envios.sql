BEGIN;

ALTER TABLE public.leads_prospeccao
    ADD COLUMN IF NOT EXISTS whatsapp_opt_in boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS whatsapp_opt_in_em timestamp with time zone,
    ADD COLUMN IF NOT EXISTS ultimo_canal_contato text;

CREATE TABLE IF NOT EXISTS public.prospeccao_envios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint NOT NULL REFERENCES public.leads_prospeccao(id) ON DELETE CASCADE,
    ordem integer NOT NULL,
    canal text NOT NULL CHECK (canal IN ('email', 'whatsapp')),
    status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'enviando', 'enviado', 'falhou', 'ignorado')),
    provider_id text,
    erro text,
    criado_em timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    iniciado_em timestamp with time zone,
    concluido_em timestamp with time zone,
    UNIQUE (lead_id, canal)
);

CREATE INDEX IF NOT EXISTS prospeccao_envios_fila_idx
    ON public.prospeccao_envios (status, ordem, id);

COMMIT;
