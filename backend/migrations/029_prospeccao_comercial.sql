BEGIN;

CREATE TABLE IF NOT EXISTS public.leads_prospeccao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text NOT NULL,
    cidade text NOT NULL DEFAULT '',
    endereco text NOT NULL DEFAULT '',
    telefone text NOT NULL DEFAULT '',
    email text NOT NULL DEFAULT '',
    site_instagram text NOT NULL DEFAULT '',
    avaliacao numeric(2,1),
    observacoes text NOT NULL DEFAULT '',
    prioridade text NOT NULL DEFAULT 'C',
    status_comercial text NOT NULL DEFAULT 'nao_contatado',
    ultimo_contato date,
    origem text NOT NULL DEFAULT 'manual',
    criado_em timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    criado_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
    atualizado_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
    excluido_em timestamp with time zone,
    excluido_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
    CONSTRAINT leads_prospeccao_prioridade_check CHECK (prioridade IN ('A', 'B', 'C')),
    CONSTRAINT leads_prospeccao_status_check CHECK (status_comercial IN (
        'nao_contatado', 'mensagem_enviada', 'respondeu', 'demonstracao',
        'interessado', 'cliente', 'nao_interessado'
    )),
    CONSTRAINT leads_prospeccao_origem_check CHECK (origem IN ('manual', 'csv', 'integracao_futura')),
    CONSTRAINT leads_prospeccao_avaliacao_check CHECK (avaliacao IS NULL OR (avaliacao >= 0 AND avaliacao <= 5))
);

CREATE INDEX IF NOT EXISTS leads_prospeccao_ativos_filtro_idx
    ON public.leads_prospeccao (prioridade, status_comercial, cidade, id)
    WHERE excluido_em IS NULL;

COMMENT ON TABLE public.leads_prospeccao IS
    'Leads comerciais globais da plataforma; nunca representam academias clientes nem são sincronizados com elas.';

COMMIT;
