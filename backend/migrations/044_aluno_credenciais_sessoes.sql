-- Credenciais e sessões do aluno no app. Migração aditiva.
BEGIN;

CREATE TABLE public.aluno_credenciais (
    aluno_id integer PRIMARY KEY REFERENCES public.alunos(id) ON DELETE CASCADE,
    senha_hash text,
    google_sub text,
    definida_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT aluno_credenciais_algum_metodo CHECK (senha_hash IS NOT NULL OR google_sub IS NOT NULL)
);
CREATE INDEX aluno_credenciais_google_sub_idx ON public.aluno_credenciais (google_sub) WHERE google_sub IS NOT NULL;

CREATE TABLE public.aluno_sessoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id integer NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
    token_hash text NOT NULL UNIQUE CHECK (char_length(token_hash) = 64),
    aparelho text NOT NULL DEFAULT '',
    criado_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em timestamptz NOT NULL,
    revogada_em timestamptz
);

CREATE INDEX aluno_sessoes_aluno_idx ON public.aluno_sessoes (aluno_id) WHERE revogada_em IS NULL;

COMMIT;
