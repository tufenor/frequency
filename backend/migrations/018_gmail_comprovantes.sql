BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.gmail_pagamento_conexoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id integer NOT NULL UNIQUE REFERENCES public.academias(id) ON DELETE CASCADE,
    usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    email text NOT NULL,
    refresh_token bytea NOT NULL,
    access_token bytea,
    access_token_expira_em timestamptz,
    ativo boolean NOT NULL DEFAULT true,
    ultima_verificacao timestamptz,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gmail_comprovantes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id integer NOT NULL REFERENCES public.academias(id) ON DELETE CASCADE,
    fatura_id bigint REFERENCES public.faturas_frequency(id) ON DELETE SET NULL,
    gmail_message_id text NOT NULL,
    remetente text NOT NULL DEFAULT '',
    assunto text NOT NULL DEFAULT '',
    recebido_em timestamptz,
    resumo text NOT NULL DEFAULT '',
    dados_extraidos jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'revisao'
        CHECK (status IN ('revisao', 'confirmado', 'ignorado')),
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    UNIQUE (academia_id, gmail_message_id)
);

CREATE INDEX IF NOT EXISTS gmail_comprovantes_academia_status_idx
    ON public.gmail_comprovantes (academia_id, status, recebido_em DESC);

COMMIT;
