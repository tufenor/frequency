BEGIN;

CREATE TABLE public.planos_frequency (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text NOT NULL UNIQUE,
    descricao text NOT NULL DEFAULT '',
    valor numeric(12, 2) NOT NULL CHECK (valor > 0),
    moeda text NOT NULL CHECK (moeda ~ '^[A-Z]{3}$'),
    duracao_dias integer NOT NULL CHECK (duracao_dias BETWEEN 1 AND 3660),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.assinaturas_frequency (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id integer NOT NULL UNIQUE REFERENCES public.academias(id) ON DELETE RESTRICT,
    plano_id bigint NOT NULL REFERENCES public.planos_frequency(id) ON DELETE RESTRICT,
    inicio date NOT NULL,
    proximo_vencimento date NOT NULL,
    status text NOT NULL DEFAULT 'ativa'
        CHECK (status IN ('ativa', 'suspensa', 'cancelada')),
    criada_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
    criada_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizada_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.faturas_frequency (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academia_id integer NOT NULL REFERENCES public.academias(id) ON DELETE RESTRICT,
    assinatura_id bigint REFERENCES public.assinaturas_frequency(id) ON DELETE RESTRICT,
    referencia text NOT NULL,
    periodo_inicio date NOT NULL,
    periodo_fim date NOT NULL,
    valor numeric(12, 2) NOT NULL CHECK (valor > 0),
    moeda text NOT NULL CHECK (moeda ~ '^[A-Z]{3}$'),
    vencimento date NOT NULL,
    status text NOT NULL DEFAULT 'em_aberto'
        CHECK (status IN ('em_aberto', 'pago', 'cancelado', 'estornado')),
    data_pagamento timestamp without time zone,
    meio_pagamento text,
    referencia_pagamento text,
    observacao_admin text NOT NULL DEFAULT '',
    criada_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
    confirmada_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
    criada_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (academia_id, periodo_inicio, periodo_fim),
    CHECK (periodo_fim >= periodo_inicio),
    CHECK ((status IN ('pago', 'estornado')) = (data_pagamento IS NOT NULL))
);

CREATE INDEX faturas_frequency_vencimento_status_idx
    ON public.faturas_frequency (vencimento, status);
CREATE INDEX faturas_frequency_academia_idx
    ON public.faturas_frequency (academia_id, status, vencimento);

CREATE TABLE public.plataforma_qrs (
    moeda text PRIMARY KEY CHECK (moeda ~ '^[A-Z]{3}$'),
    imagem bytea NOT NULL,
    media_type text NOT NULL CHECK (media_type IN ('image/png', 'image/jpeg', 'image/webp')),
    atualizado_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
    atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (octet_length(imagem) BETWEEN 1 AND 2097152)
);

CREATE TABLE public.configuracao_frequency (
    id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    contato_email text,
    contato_telefone text,
    atualizada_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO public.configuracao_frequency (id) VALUES (1);

CREATE TABLE public.auditoria_frequency (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ator_id integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
    acao text NOT NULL,
    entidade text NOT NULL,
    entidade_id text,
    detalhes jsonb NOT NULL DEFAULT '{}'::jsonb,
    criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX auditoria_frequency_data_idx
    ON public.auditoria_frequency (criado_em DESC, id DESC);

COMMENT ON TABLE public.faturas_frequency IS
    'Faturas da assinatura do software Frequency; não são mensalidades de alunos.';
COMMENT ON TABLE public.plataforma_qrs IS
    'QRs de recebimento do Frequency por moeda, separados do QR que cada academia recebe dos alunos.';
COMMENT ON TABLE public.auditoria_frequency IS
    'Registra ações administrativas sobre pacotes, faturas e configuração do Frequency.';
COMMENT ON COLUMN public.assinaturas_frequency.status IS
    'Situação comercial; bloqueio por atraso considera a fatura Frequency aberta mais antiga.';

COMMIT;
