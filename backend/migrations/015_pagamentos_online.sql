BEGIN;

-- Estado técnico da cobrança externa. O status financeiro continua sendo o
-- status da fatura; estes campos permitem repetir notificações sem duplicar a
-- baixa e permitem o cliente voltar ao checkout já criado.
ALTER TABLE public.faturas_frequency
    ADD COLUMN provedor_pagamento text,
    ADD COLUMN pagamento_id_externo text,
    ADD COLUMN pedido_pagamento_externo text,
    ADD COLUMN checkout_url text,
    ADD COLUMN status_pagamento_externo text NOT NULL DEFAULT 'nao_criado',
    ADD COLUMN pagamento_atualizado_em timestamp without time zone;

ALTER TABLE public.faturas_frequency
    ADD CONSTRAINT faturas_frequency_status_pagamento_check
    CHECK (status_pagamento_externo IN ('nao_criado', 'criando', 'pendente', 'pago', 'recusado', 'erro'));

CREATE UNIQUE INDEX faturas_frequency_pagamento_id_uq
    ON public.faturas_frequency (provedor_pagamento, pagamento_id_externo)
    WHERE pagamento_id_externo IS NOT NULL;

CREATE UNIQUE INDEX faturas_frequency_pedido_pagamento_uq
    ON public.faturas_frequency (provedor_pagamento, pedido_pagamento_externo)
    WHERE pedido_pagamento_externo IS NOT NULL;

CREATE TABLE public.pagamentos_webhook_eventos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provedor text NOT NULL,
    chave_evento text NOT NULL,
    pagamento_id_externo text,
    pedido_pagamento_externo text,
    status_externo text,
    valor numeric(12, 2),
    moeda text,
    payload_hash text NOT NULL,
    estado text NOT NULL DEFAULT 'recebido'
        CHECK (estado IN ('recebido', 'processado', 'ignorado', 'rejeitado', 'erro')),
    motivo text,
    recebido_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processado_em timestamp without time zone,
    UNIQUE (provedor, chave_evento)
);

CREATE INDEX pagamentos_webhook_eventos_pagamento_idx
    ON public.pagamentos_webhook_eventos (provedor, pagamento_id_externo, recebido_em DESC);

COMMENT ON COLUMN public.faturas_frequency.pedido_pagamento_externo IS
    'Referência idempotente enviada ao gateway; nunca é o comprovante isolado do cliente.';
COMMENT ON TABLE public.pagamentos_webhook_eventos IS
    'Recebe eventos assinados de gateways; não guarda o payload completo nem documentos do pagador.';

COMMIT;
